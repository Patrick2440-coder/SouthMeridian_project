	<script>
const registerLocations =
    <?= json_encode(
        array_values($southMeridianLocations),
        JSON_UNESCAPED_UNICODE |
        JSON_UNESCAPED_SLASHES
    ) ?>;


document.addEventListener(
    'DOMContentLoaded',
    function () {

        const blockSelect =
            document.getElementById(
                'registerBlock'
            );

        const lotSelect =
            document.getElementById(
                'registerLot'
            );

        const propertyInfo =
            document.getElementById(
                'selectedPropertyInfo'
            );


        if (
            !blockSelect ||
            !lotSelect
        ) {
            return;
        }


        /*
        |--------------------------------------------------------------------------
        | Build Block list
        |--------------------------------------------------------------------------
        */

        const blocks =
            [
                ...new Set(
                    registerLocations.map(
                        item =>
                            Number(
                                item.block
                            )
                    )
                )
            ]
            .filter(
                Number.isFinite
            )
            .sort(
                (a, b) =>
                    a - b
            );


        blocks.forEach(
            block => {

                const option =
                    document.createElement(
                        'option'
                    );

                option.value =
                    block;

                option.textContent =
                    'Block ' + block;

                blockSelect.appendChild(
                    option
                );
            }
        );


        /*
        |--------------------------------------------------------------------------
        | Block changed
        |--------------------------------------------------------------------------
        */

        blockSelect.addEventListener(
            'change',
            function () {

                const block =
                    Number(
                        this.value
                    );


                lotSelect.innerHTML =
                    '<option value="">Select Lot</option>';


                propertyInfo.innerHTML =
                    'Select a Lot.';


                if (!block) {

                    lotSelect.disabled =
                        true;

                    return;
                }


                const lots =
                    registerLocations
                        .filter(
                            item =>
                                Number(
                                    item.block
                                ) === block
                        )
                        .sort(
                            (a, b) =>
                                Number(a.lot) -
                                Number(b.lot)
                        );


                lots.forEach(
                    item => {

                        const option =
                            document.createElement(
                                'option'
                            );

                        option.value =
                            item.lot;

                        option.textContent =
                            'Lot ' +
                            item.lot;

                        lotSelect.appendChild(
                            option
                        );
                    }
                );


                lotSelect.disabled =
                    false;
            }
        );


        /*
        |--------------------------------------------------------------------------
        | Lot changed
        |--------------------------------------------------------------------------
        */

        lotSelect.addEventListener(
            'change',
            function () {

                const block =
                    Number(
                        blockSelect.value
                    );

                const lot =
                    Number(
                        lotSelect.value
                    );


                const location =
                    registerLocations.find(
                        item =>
                            Number(
                                item.block
                            ) === block
                            &&
                            Number(
                                item.lot
                            ) === lot
                    );


                if (!location) {

                    propertyInfo.innerHTML =
                        'Select a valid property.';

                    return;
                }


                propertyInfo.innerHTML =
                    '<strong>Selected Property:</strong> ' +
                    'Block ' +
                    block +
                    ', Lot ' +
                    lot +
                    (
                        location.street
                            ? ' · ' +
                              location.street
                            : ''
                    );
            }
        );

    }
);
</script>
