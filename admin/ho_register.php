function normalizePhase($phase){
    $phase = trim((string)$phase);

    $allowed = [
        'Phase 1',
        'Phase 2',
        'Phase 3'
    ];

    return in_array(
        $phase,
        $allowed,
        true
    )
        ? $phase
        : '';
}

/*
|--------------------------------------------------------------------------
| Secure document upload
|--------------------------------------------------------------------------
*/
function saveRegistrationDocument(
    array $file,
    string $documentType
): string {

    /*
     * Allowed document types used in the filename.
     */
    if (
        !in_array(
            $documentType,
            ['id', 'proof'],
            true
        )
    ) {
        throw new RuntimeException(
            'Invalid document type.'
        );
    }


    /*
     * Make sure PHP received a normal upload.
     */
    if (
        !isset($file['error']) ||
        is_array($file['error'])
    ) {
        throw new RuntimeException(
            'Invalid uploaded file.'
        );
    }


    switch ($file['error']) {

        case UPLOAD_ERR_OK:
            break;

        case UPLOAD_ERR_NO_FILE:
            throw new RuntimeException(
                'Please select the required document.'
            );

        case UPLOAD_ERR_INI_SIZE:
        case UPLOAD_ERR_FORM_SIZE:
            throw new RuntimeException(
                'The uploaded document is too large.'
            );

        default:
            throw new RuntimeException(
                'The document upload failed.'
            );
    }


    /*
     * Maximum file size: 5 MB.
     */
    $maxSize =
        5 * 1024 * 1024;


    if (
        (int)($file['size'] ?? 0) <= 0 ||
        (int)$file['size'] > $maxSize
    ) {

        throw new RuntimeException(
            'Documents must be 5 MB or smaller.'
        );
    }


    $tmpName =
        (string)($file['tmp_name'] ?? '');


    if (
        $tmpName === '' ||
        !is_uploaded_file($tmpName)
    ) {

        throw new RuntimeException(
            'Invalid uploaded document.'
        );
    }


    /*
     * Detect the REAL file MIME type.
     * Never trust $_FILES["type"].
     */
    $finfo =
        new finfo(
            FILEINFO_MIME_TYPE
        );


    $mimeType =
        $finfo->file(
            $tmpName
        );


    $allowedTypes = [

        'image/jpeg' =>
            'jpg',

        'image/png' =>
            'png',

        'application/pdf' =>
            'pdf'
    ];


    if (
        !isset(
            $allowedTypes[
                $mimeType
            ]
        )
    ) {

        throw new RuntimeException(
            'Only JPG, PNG, and PDF documents are allowed.'
        );
    }


    $extension =
        $allowedTypes[
            $mimeType
        ];


    /*
     * Project-root uploads directory.
     */
    $uploadDirFs =
        dirname(__DIR__) .
        DIRECTORY_SEPARATOR .
        'uploads' .
        DIRECTORY_SEPARATOR;


    if (
        !is_dir($uploadDirFs) &&
        !mkdir(
            $uploadDirFs,
            0755,
            true
        )
    ) {

        throw new RuntimeException(
            'Unable to create upload directory.'
        );
    }


    /*
     * Random server-generated filename.
     *
     * Example:
     * 28ba8f...._id.jpg
     */
    $fileName =
        bin2hex(
            random_bytes(16)
        ) .
        '_' .
        $documentType .
        '.' .
        $extension;


    $filePath =
        $uploadDirFs .
        $fileName;


    if (
        !move_uploaded_file(
            $tmpName,
            $filePath
        )
    ) {

        throw new RuntimeException(
            'Failed to save uploaded document.'
        );
    }


    /*
     * Path stored in database.
     */
    return
        'uploads/' .
        $fileName;
}


/*
|--------------------------------------------------------------------------
| Verify a document carried from Step 1 to Step 2
|--------------------------------------------------------------------------
*/
function validRegistrationDocument(
    string $dbPath,
    string $documentType
): bool {

    if (
        !in_array(
            $documentType,
            ['id', 'proof'],
            true
        )
    ) {
        return false;
    }


    /*
     * Only accept filenames generated by
     * saveRegistrationDocument().
     */
    $pattern =
        '~^uploads/' .
        '[a-f0-9]{32}_' .
        preg_quote(
            $documentType,
            '~'
        ) .
        '\.(?:jpg|png|pdf)$~D';


    if (
        !preg_match(
            $pattern,
            $dbPath
        )
    ) {

        return false;
    }


    $fullPath =
        dirname(__DIR__) .
        DIRECTORY_SEPARATOR .
        str_replace(
            '/',
            DIRECTORY_SEPARATOR,
            $dbPath
        );


    return is_file(
        $fullPath
    );
}

/*
|--------------------------------------------------------------------------
| Official South Meridian Block / Lot Mapping
|--------------------------------------------------------------------------
*/
function loadSouthMeridianLocations(): array
{
    $path =
        __DIR__ .
        '/southmeri_block_lot_mapping.json';

    if (!is_readable($path)) {
        throw new RuntimeException(
            'South Meridian Block/Lot mapping file was not found.'
        );
    }

    $decoded =
        json_decode(
            (string) file_get_contents($path),
            true
        );

    if (!is_array($decoded)) {
        throw new RuntimeException(
            'South Meridian Block/Lot mapping file is invalid.'
        );
    }


    $pageWidthEmu =
        8.5 * 914400;

    $pageHeightEmu =
        11 * 914400;

    $pageMarginEmu =
        914400;

    $markerCenterOffsetEmu =
        90000;


    $locations = [];


    foreach ($decoded as $item) {

        $block =
            (int)($item['block'] ?? 0);

        $lot =
            (int)($item['lot'] ?? 0);


        if (
            $block <= 0 ||
            $lot <= 0
        ) {
            continue;
        }


        $xEmu =
            (float)($item['x_emu'] ?? 0);

        $yEmu =
            (float)($item['y_emu'] ?? 0);


        $mapX =
            (int) round(
                (
                    (
                        $pageMarginEmu +
                        $xEmu +
                        $markerCenterOffsetEmu
                    )
                    /
                    $pageWidthEmu
                )
                * 2550
            );


        $mapY =
            (int) round(
                (
                    (
                        $pageMarginEmu +
                        $yEmu +
                        $markerCenterOffsetEmu
                    )
                    /
                    $pageHeightEmu
                )
                * 3300
            );


        $locations[
            $block . ':' . $lot
        ] = [
            'block' =>
                $block,

            'lot' =>
                $lot,

            'street' =>
                trim(
                    (string)(
                        $item['street'] ?? ''
                    )
                ),

            'map_x' =>
                $mapX,

            'map_y' =>
                $mapY
        ];
    }


    return $locations;
}

